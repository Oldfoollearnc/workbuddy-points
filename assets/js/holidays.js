/**
 * 中国法定节假日（用于"工作日折算"）
 * 说明：只影响"每天/每周可用积分"的估算，不影响任何真实数据。
 * 数据可按年更新；未列出的年份按"周一至周五为工作日"处理。
 */
(function () {
  const RANGES = {
    2025: [
      ['2025-01-01', '2025-01-01'], // 元旦
      ['2025-01-28', '2025-02-04'], // 春节
      ['2025-04-04', '2025-04-06'], // 清明
      ['2025-05-01', '2025-05-05'], // 劳动节
      ['2025-05-31', '2025-06-02'], // 端午
      ['2025-10-01', '2025-10-08'], // 国庆 + 中秋
    ],
    2026: [
      ['2026-01-01', '2026-01-03'], // 元旦
      ['2026-02-16', '2026-02-22'], // 春节（除夕 2/16）
      ['2026-04-04', '2026-04-06'], // 清明
      ['2026-05-01', '2026-05-05'], // 劳动节
      ['2026-06-19', '2026-06-21'], // 端午
      ['2026-09-25', '2026-09-27'], // 中秋
      ['2026-10-01', '2026-10-07'], // 国庆
    ],
    2027: [
      ['2027-01-01', '2027-01-03'],
      ['2027-02-05', '2027-02-11'],
      ['2027-04-03', '2027-04-05'],
      ['2027-05-01', '2027-05-05'],
      ['2027-06-09', '2027-06-11'],
      ['2027-10-01', '2027-10-07'],
    ]
  };

  const set = new Set();
  Object.values(RANGES).forEach(list => {
    list.forEach(([a, b]) => {
      const start = new Date(a + 'T00:00:00');
      const end = new Date(b + 'T00:00:00');
      for (let d = new Date(start); d <= end; d.setDate(d.getDate() + 1)) {
        set.add(`${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`);
      }
    });
  });

  window.HOLIDAYS = {
    has(date) {
      const k = `${date.getFullYear()}-${String(date.getMonth() + 1).padStart(2, '0')}-${String(date.getDate()).padStart(2, '0')}`;
      return set.has(k);
    }
  };
})();
